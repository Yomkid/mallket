// src/utils/notification.ts

import prisma from '../config/prisma';
import { NotificationType } from '@prisma/client'; // assuming it's generated by Prisma

type NotificationParams = {
    userId: string;
    //   type: 'INFO' | 'WARNING' | 'SUCCESS' | 'ERROR'; // Match your NotificationType enum
    type: NotificationType;
    title: string;
    message: string;
    link?: string; // optional URL to redirect user
};


export const sendNotification = async ({
    userId,
    type,
    title,
    message,
    link,
}: NotificationParams) => {
    try {
        await prisma.notification.create({
            data: {
                userId,
                type,
                title,
                message,
                link,
            },
        });
    } catch (error) {
        console.error("❌ Failed to send notification:", error);
        // You may log this in auditLog or a monitoring service
    }
};



// Optionally send to many users

export const sendBulkNotifications = async (
  users: string[],
  title: string,
  message: string,
  type: NotificationType = NotificationType.INFO // default type if you want
) => {
  const notifications = users.map(userId => ({
    userId,
    title,
    message,
    type,       // <- required field added here
    isRead: false,
  }));

  return await prisma.notification.createMany({
    data: notifications,
  });
};



